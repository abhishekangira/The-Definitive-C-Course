#!/usr/bin/env node
// check.mjs -- zero-dependency local test runner for course exercises (check50-style).
//
//   node check.mjs [exercise-dir] [--src file.c] [--verbose] [--json] [--only "name"]
//
// Works on macOS (Apple clang from Xcode CLT), Linux and WSL (gcc or clang). Node >= 18.
// Reads <exercise-dir>/check.json. Exit code 0 = all tests passed.
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir, platform as osPlatform, arch } from "node:os";
import { basename, dirname, join, resolve } from "node:path";

// ---------------------------------------------------------------- cli / config
const argv = process.argv.slice(2);
const flag = (f) => argv.includes(f);
const optv = (f) => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : undefined; };
const positional = argv.filter((a, i) => !a.startsWith("--") && !["--src", "--only", "--cc"].includes(argv[i - 1]));
const exDir = resolve(positional[0] ?? ".");
const cfgPath = join(exDir, "check.json");
if (!existsSync(cfgPath)) die(`No check.json in ${exDir}. Run this from an exercise folder, or pass its path.`);
const cfg = JSON.parse(readFileSync(cfgPath, "utf8"));
const sources = (optv("--src") ? [resolve(optv("--src"))] : cfg.sources.map((s) => join(exDir, s)));
const VERBOSE = flag("--verbose"), JSON_OUT = flag("--json"), ONLY = optv("--only");
const PLATFORM = process.env.CHECK_PLATFORM ?? osPlatform(); // override only for testing the runner
const TIMEOUT = cfg.timeoutMs ?? 2000;

// ---------------------------------------------------------------- output helpers
const tty = process.stdout.isTTY && !process.env.NO_COLOR && !JSON_OUT;
const paint = (code) => (s) => (tty ? `\x1b[${code}m${s}\x1b[0m` : s);
const green = paint(32), red = paint(31), yellow = paint(33), dim = paint(2), bold = paint(1), cyan = paint(36);
const unicode = PLATFORM !== "win32";
const MARK = { pass: green(unicode ? "✓" : "+"), fail: red(unicode ? "✗" : "x"), skip: yellow(unicode ? "–" : "-") };
const show = (s, max = 400) => {
  if (s === undefined || s === null) return dim("(nothing)");
  // invalid UTF-8 (e.g. a char pushed past 'z') -> show bytes as \xNN instead of U+FFFD
  const t = s.replace(/[\u0080-\u00ff]/g, (c) => `\\x${c.charCodeAt(0).toString(16)}`);
  const q = JSON.stringify(t.length > max ? t.slice(0, max) + "…" : t).replace(/\\\\x/g, "\\x");
  return q === '""' ? dim('"" (no output)') : q;
};
function die(msg) { console.error(msg); process.exit(2); }

// ---------------------------------------------------------------- toolchain
function decode(buf) {             // UTF-8 if valid, else latin1 so every byte stays visible
  if (!buf) return "";
  const u = buf.toString("utf8");
  return Buffer.from(u, "utf8").equals(buf) ? u : buf.toString("latin1");
}
function sh(cmd, args, opts = {}) {
  const t0 = Date.now();
  const r = spawnSync(cmd, args, { maxBuffer: 8 << 20, ...opts });
  return { status: r.status, signal: r.signal, stdout: decode(r.stdout), stderr: decode(r.stderr),
           timedOut: r.error?.code === "ETIMEDOUT", missing: r.error?.code === "ENOENT", ms: Date.now() - t0 };
}
const has = (cmd, args = ["--version"]) => !sh(cmd, args).missing;

function pickCompiler() {
  for (const cc of [optv("--cc"), process.env.CC, "cc", "clang", "gcc"].filter(Boolean)) {
    const r = sh(cc, ["--version"]);
    if (!r.missing && r.status === 0) return { cc, version: r.stdout.split("\n")[0], apple: /Apple clang/.test(r.stdout) };
  }
  die(PLATFORM === "darwin"
    ? "No C compiler found. Install the Xcode Command Line Tools:  xcode-select --install"
    : "No C compiler found. Install one:  sudo apt install build-essential   (Ubuntu / WSL)");
}
const tc = pickCompiler();
const work = mkdtempSync(join(tmpdir(), `check-${cfg.name ?? "ex"}-`));
process.on("exit", () => { if (!flag("--keep")) rmSync(work, { recursive: true, force: true }); });

const CFLAGS = ["-std=c17", "-Wall", "-Wextra", "-pedantic", "-g", "-O0", ...(cfg.cflags ?? [])];
const SAN = ["-fsanitize=address,undefined", "-fno-omit-frame-pointer", "-fno-sanitize-recover=all"];
const LIBS = cfg.libs ?? ["-lm"];

writeFileSync(join(work, "check.h"), `/* generated by check.mjs */
#ifndef CHECK_H
#define CHECK_H
#include <stdio.h>
#include <string.h>
static int check_failures_ = 0;
#define CHECK_REPORT_(ok, name, ...) do { if (ok) { printf("@@PASS %s\\n", name); } else { \\
    printf("@@FAIL %s\\t", name); printf(__VA_ARGS__); printf("\\n"); check_failures_++; } \\
    fflush(stdout); } while (0)
#define CHECK(cond, name) CHECK_REPORT_((cond), name, "condition was false: %s", #cond)
#define CHECK_EQ_INT(actual, expected, name) do { long long a_ = (actual), e_ = (expected); \\
    CHECK_REPORT_(a_ == e_, name, "expected %lld, got %lld", e_, a_); } while (0)
#define CHECK_EQ_CHAR(actual, expected, name) do { int a_ = (unsigned char)(actual), e_ = (unsigned char)(expected); \\
    CHECK_REPORT_(a_ == e_, name, "expected '%c' (%d), got '%c' (%d)", e_ >= 32 && e_ < 127 ? e_ : '?', e_, \\
                  a_ >= 32 && a_ < 127 ? a_ : '?', a_); } while (0)
#define CHECK_EQ_STR(actual, expected, name) do { const char *a_ = (actual), *e_ = (expected); \\
    CHECK_REPORT_(a_ && e_ && strcmp(a_, e_) == 0, name, "expected \\"%s\\", got %s%s%s", e_, a_ ? "\\"" : "", a_ ? a_ : "NULL", a_ ? "\\"" : ""); } while (0)
#define CHECK_RESULT() (check_failures_ ? 1 : 0)
#endif
`);

const builds = {};
function build(kind) {               // kind: "plain" | "asan" | "unit:<harness>"
  if (builds[kind]) return builds[kind];
  const out = join(work, kind.replace(/[^\w]/g, "_"));
  let args;
  if (kind.startsWith("unit:")) {
    const harness = join(exDir, kind.slice(5));
    args = [...CFLAGS, `-I${work}`, `-DLEARNER_SRC="${sources[0]}"`, ...(caps().sanitizers ? SAN : []), harness, "-o", out, ...LIBS];
  } else {
    args = [...CFLAGS, ...(kind === "asan" ? SAN : []), ...sources, "-o", out, ...LIBS];
  }
  const r = sh(tc.cc, ["-fdiagnostics-color=never", ...args], { cwd: exDir });
  const warnings = [...r.stderr.matchAll(/^(.*?):(\d+):(\d+): warning: (.*)$/gm)].map((m) => `${basename(m[1])}:${m[2]}: ${m[4]}`);
  const errors = [...r.stderr.matchAll(/^(.*?):(\d+):(\d+): (?:fatal )?error: (.*)$/gm)].map((m) => `${basename(m[1])}:${m[2]}: ${m[4]}`);
  return (builds[kind] = { ok: r.status === 0, exe: out, stderr: r.stderr, warnings, errors, cmd: `${tc.cc} ${args.join(" ")}` });
}

let capsCache;
function caps() {                    // probe once: can we build+run sanitizer binaries? valgrind? leaks?
  if (capsCache) return capsCache;
  const src = join(work, "probe.c");
  writeFileSync(src, "#include <stdlib.h>\nint main(void){ free(malloc(1)); return 0; }\n");
  const san = sh(tc.cc, [...SAN, src, "-o", join(work, "probe")]);
  const sanRun = san.status === 0 ? sh(join(work, "probe"), [], { env: sanEnv() }) : { status: 1 };
  capsCache = {
    sanitizers: !process.env.CHECK_NO_SANITIZERS && san.status === 0 && sanRun.status === 0,
    sanitizerWhy: san.status !== 0 ? san.stderr.split("\n").find((l) => /error|cannot find/.test(l)) : null,
    // LeakSanitizer: on by default on Linux x86_64/aarch64; Apple's clang runtime aborts
    // with "detect_leaks is not supported on this platform", so use `leaks` there.
    lsan: PLATFORM === "linux",
    valgrind: PLATFORM === "linux" && has("valgrind"),
    leaks: PLATFORM === "darwin" && has("leaks", ["--help"]),
  };
  return capsCache;
}
function sanEnv() {
  return { ...process.env,
    ASAN_OPTIONS: `detect_leaks=${PLATFORM === "linux" ? 1 : 0}:abort_on_error=0:exitcode=86:color=never`,
    UBSAN_OPTIONS: "print_stacktrace=1:halt_on_error=1:exitcode=87:color=never",
    MallocNanoZone: "0" };  // silences a known macOS ASan malloc warning
}

// ---------------------------------------------------------------- matching
function match(spec, actual) {       // spec: string (exact) | {equals|contains|matches|trim}
  if (spec === undefined) return { ok: true };
  const s = typeof spec === "string" ? { equals: spec } : spec;
  let a = actual ?? "";
  if (s.trim) a = a.trim();
  if (s.equals !== undefined && a !== (s.trim ? s.equals.trim() : s.equals)) return { ok: false, want: s.equals, how: "exactly" };
  if (s.contains !== undefined && !a.includes(s.contains)) return { ok: false, want: s.contains, how: "containing" };
  if (s.matches !== undefined && !new RegExp(s.matches, s.flags ?? "").test(a)) return { ok: false, want: `/${s.matches}/`, how: "matching", raw: true };
  return { ok: true };
}
function firstDiff(want, got) {      // point at the first differing character
  let i = 0;
  while (i < want.length && i < got.length && want[i] === got[i]) i++;
  const lineNo = want.slice(0, i).split("\n").length;
  return `first difference on line ${lineNo}, character ${i - want.lastIndexOf("\n", i - 1)}`;
}
const SIGNALS = { SIGSEGV: "a segmentation fault (it touched memory it doesn't own -- often a NULL or out-of-bounds pointer)",
  SIGABRT: "an abort (often a failed assert, or the C library detecting heap corruption)",
  SIGFPE: "a floating-point exception (usually integer division by zero)", SIGBUS: "a bus error (misaligned or invalid memory access)" };

function cmdline(t) {
  const bin = `./${cfg.binary ?? basename(sources[0], ".c")}`;
  const a = (t.args ?? []).map((x) => (/[\s"'$]/.test(x) || x === "" ? JSON.stringify(x) : x)).join(" ");
  return `${bin}${a ? " " + a : ""}${t.stdin !== undefined ? `   with input ${show(t.stdin, 80)}` : ""}`;
}

// ---------------------------------------------------------------- test kinds
function runIO(t, exe, env) {
  const r = sh(exe, t.args ?? [], { input: t.stdin ?? "", timeout: t.timeoutMs ?? TIMEOUT, killSignal: "SIGKILL", cwd: exDir, env });
  const details = [`ran:       ${cmdline(t)}`];
  if (r.timedOut) return { status: "fail", details: [...details, `it was still running after ${(t.timeoutMs ?? TIMEOUT) / 1000}s -- an infinite loop, or is it waiting for input it never gets?`], r };
  if (r.signal) return { status: "fail", details: [...details, `it crashed with ${SIGNALS[r.signal] ?? r.signal}`, ...(r.stdout ? [`output before the crash: ${show(r.stdout)}`] : [])], r };
  for (const [stream, spec] of [["stdout", t.stdout], ["stderr", t.stderr]]) {
    const m = match(spec, r[stream]);
    if (!m.ok) {
      const d = [...details, `expected ${stream} ${m.how}: ${m.raw ? m.want : show(m.want)}`, `actual ${stream}:${" ".repeat(Math.max(1, 17 - stream.length - 8))}${show(r[stream])}`];
      if (m.how === "exactly" && r[stream]) d.push(dim(firstDiff(m.want, r[stream])));
      return { status: "fail", details: d, r };
    }
  }
  const wantExit = t.exit ?? (t.type === "memory" ? undefined : 0);
  if (wantExit !== undefined && r.status !== wantExit) {
    return { status: "fail", details: [...details, `expected exit code ${wantExit}, got ${r.status}`, ...(r.stderr ? [`stderr: ${show(r.stderr, 300)}`] : [])], r };
  }
  for (const [file, spec] of Object.entries(t.files ?? {})) {
    const p = join(exDir, file);
    if (!existsSync(p)) return { status: "fail", details: [...details, `expected it to create ${file}, but it doesn't exist`], r };
    const m = match(spec, readFileSync(p, "utf8"));
    if (!m.ok) return { status: "fail", details: [...details, `${file} should be ${m.how} ${show(m.want)}`], r };
  }
  return { status: "pass", r };
}

function sanitizerSummary(stderr) {
  const kind = /ERROR: (AddressSanitizer|LeakSanitizer): ([\w-]+)/.exec(stderr) ?? /runtime error: (.*)/.exec(stderr);
  if (!kind) return null;
  const src = new Set(sources.map((s) => basename(s)));
  const frames = [...stderr.matchAll(/#\d+ 0x[0-9a-f]+ in (\w+) (\S+?):(\d+)/g)]
    .filter((m) => src.has(basename(m[2]))).map((m) => `${m[1]}() at ${basename(m[2])}:${m[3]}`);
  const access = /^(READ|WRITE) of size (\d+)/m.exec(stderr);
  const where = /is located (\d+) bytes (after|before|inside) (?:of )?(\d+)-byte region/.exec(stderr);
  const lines = [];
  if (kind[1] === "LeakSanitizer") {
    const leaks = [...stderr.matchAll(/(Direct|Indirect) leak of (\d+) byte\(s\) in (\d+) object/g)];
    lines.push(`memory leak: ${leaks.reduce((n, m) => n + +m[2], 0)} byte(s) malloc'd but never freed`);
  } else if (kind[1] === "AddressSanitizer") {
    lines.push(`${kind[2]}${access ? `: ${access[1].toLowerCase()} of ${access[2]} byte(s)` : ""}` +
      (where ? ` ${where[1]} bytes ${where[2]} a ${where[3]}-byte block` : ""));
  } else lines.push(`undefined behavior: ${kind[1]}`);
  if (frames.length) lines.push(`at ${frames[0]}${frames[1] ? ` (block allocated at ${frames.at(-1)})` : ""}`);
  return lines;
}

function memoryTest(t) {
  const c = caps();
  const notes = [], details = [`ran:       ${cmdline(t)}`];
  let ran = false;
  if (c.sanitizers) {
    const b = build("asan");
    if (!b.ok) return { status: "fail", details: ["did not compile with sanitizers", ...b.errors] };
    const res = runIO({ ...t, stdout: undefined, stderr: undefined, exit: undefined }, b.exe, sanEnv());
    ran = true;
    const sum = sanitizerSummary(res.r?.stderr ?? "");
    if (sum) return { status: "fail", details: [...details, ...sum], hint: t.hint ?? "Run it yourself to see the full report: build with -fsanitize=address,undefined -g" };
    if (res.status === "fail") return res;
    notes.push(c.lsan ? "AddressSanitizer + UBSan + LeakSanitizer" : "AddressSanitizer + UBSan");
  } else notes.push("sanitizers not installed for this compiler");

  if (c.valgrind && (t.valgrind ?? (!c.sanitizers ? true : cfg.valgrind ?? false))) {
    const b = build("plain");
    const r = sh("valgrind", ["-q", "--error-exitcode=99", "--leak-check=full", "--errors-for-leak-kinds=definite,indirect",
      "--show-leak-kinds=definite,indirect", b.exe, ...(t.args ?? [])], { input: t.stdin ?? "", timeout: 20000, cwd: exDir });
    ran = true;
    if (r.status === 99) {
      const first = /^==\d+== (Invalid .*|Conditional jump .*|Use of uninitialised .*|\d+ bytes in \d+ blocks are definitely lost.*)$/m.exec(r.stderr);
      const at = new RegExp(`[(/](${sources.map((s) => basename(s).replace(/\./g, "\\.")).join("|")}):(\\d+)\\)`).exec(r.stderr);
      return { status: "fail", details: [...details, `valgrind: ${first ? first[1] : "memory error"}`, ...(at ? [`at ${at[1]}:${at[2]}`] : [])] };
    }
    notes.push("valgrind");
  }
  if (c.leaks && t.leaks !== false) {
    // macOS: Apple clang's ASan can't detect leaks -> run the plain build under leaks(1).
    const b = build("plain");
    const r = sh("leaks", ["--atExit", "--", b.exe, ...(t.args ?? [])],
      { input: t.stdin ?? "", timeout: 30000, cwd: exDir, env: { ...process.env, MallocStackLogging: "1" } });
    ran = true;
    const m = /(\d+) leaks? for (\d+) total leaked bytes/.exec(r.stdout);
    if (m && +m[1] > 0) {
      const at = new RegExp(`(${sources.map((s) => basename(s)).join("|")}):(\\d+)`).exec(r.stdout);
      return { status: "fail", details: [...details, `memory leak: ${m[1]} block(s), ${m[2]} byte(s) never freed`, ...(at ? [`allocated at ${at[0]}`] : [])] };
    }
    notes.push("leaks --atExit");
  }
  if (!ran) return { status: "skip", details: ["no memory checker available on this machine"] };
  if (!(c.sanitizers && c.lsan) && !notes.includes("valgrind") && !notes.includes("leaks --atExit"))
    notes.push(yellow("leaks NOT checked: no leak detector found"));
  return { status: "pass", note: notes.join(", ") };
}

function unitTest(t) {
  const b = build(`unit:${t.harness}`);
  if (!b.ok) return { status: "fail", details: ["the unit tests did not compile against your code:", ...b.errors.slice(0, 5)] };
  const r = sh(b.exe, [], { timeout: t.timeoutMs ?? TIMEOUT, killSignal: "SIGKILL", cwd: exDir, env: sanEnv() });
  const subs = [...r.stdout.matchAll(/^@@(PASS|FAIL) ([^\t\n]*)(?:\t(.*))?$/gm)].map((m) => ({ ok: m[1] === "PASS", name: m[2], why: m[3] }));
  const crashed = r.timedOut || r.signal || (r.status !== 0 && r.status !== 1);
  if (crashed) {
    const sum = sanitizerSummary(r.stderr);
    subs.push({ ok: false, name: "(remaining unit tests)", why: r.timedOut ? "timed out" : sum ? sum.join("; ") : `crashed (${r.signal ?? "exit " + r.status})` });
  }
  return { status: subs.every((s) => s.ok) && subs.length ? "pass" : "fail", subs };
}

function compileTest(t) {
  const b = build("plain");
  if (!b.ok) return { status: "fail", details: ["your code doesn't compile yet:", ...b.errors.slice(0, 5).map((e) => red(e))], verbose: b.stderr };
  if (t.warnings === false && b.warnings.length) return { status: "fail", details: [`${b.warnings.length} warning(s):`, ...b.warnings.slice(0, 5)], verbose: b.stderr };
  return { status: "pass" };
}

// ---------------------------------------------------------------- main
const results = [];
if (!JSON_OUT) {
  console.log(`\n${bold(cfg.title ?? cfg.name)}  ${dim(`(${sources.map((s) => basename(s)).join(", ")})`)}`);
  console.log(dim(`${tc.version} · ${PLATFORM}-${arch()}\n`));
}
for (const t of cfg.tests) {
  if (ONLY && t.name !== ONLY) continue;
  let res;
  const kind = t.type ?? "run";
  if (kind !== "compile" && !build("plain").ok) res = { status: "skip", details: ["can't check until it compiles"] };
  else if (kind === "compile") res = compileTest(t);
  else if (kind === "unit") res = unitTest(t);
  else if (kind === "memory") res = memoryTest(t);
  else res = runIO(t, build("plain").exe);
  delete res.r;
  results.push({ name: t.name, type: kind, ...res, hint: res.status === "fail" ? res.hint ?? t.hint : undefined });
  if (JSON_OUT) continue;
  console.log(`${MARK[res.status]} ${res.status === "fail" ? bold(t.name) : t.name}${res.note ? dim(`  (${res.note})`) : ""}`);
  for (const s of res.subs ?? []) console.log(`    ${s.ok ? MARK.pass : MARK.fail} ${s.name}${s.why ? "\n        " + s.why : ""}`);
  if (res.status !== "pass") for (const d of res.details ?? []) console.log(`    ${d}`);
  if (res.status === "fail" && (res.hint ?? t.hint)) console.log(`    ${cyan("hint:")} ${res.hint ?? t.hint}`);
  if (VERBOSE && res.verbose) console.log(dim(res.verbose.replace(/^/gm, "    | ")));
}
const passed = results.filter((r) => r.status === "pass").length;
if (JSON_OUT) console.log(JSON.stringify({ exercise: cfg.name, compiler: tc.version, platform: `${PLATFORM}-${arch()}`, passed, total: results.length, results }, null, 2));
else {
  const all = passed === results.length;
  console.log(`\n${all ? green(bold(`All ${passed} checks passed.`)) : `${bold(`${passed}/${results.length}`)} checks passed.`}` +
    (all ? "" : dim("  Fix the first failure, then run `node check.mjs` again.")));
}
process.exitCode = passed === results.length ? 0 : 1;
