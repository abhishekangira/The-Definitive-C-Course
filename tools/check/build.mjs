#!/usr/bin/env node
// Builds the local test runner and (for CI) reference project zips.
//
//   node tools/check/build.mjs                  bundle tools/check/src/check.ts → dist-tools/check.mjs
//   node tools/check/build.mjs --into dist      …and copy it to dist/downloads/check.mjs (npm run build does this)
//   node tools/check/build.mjs --zip <dir> --out <file.zip> [--solution] [--seed HEX]
//                                               build a project zip from a project, LT exercise or variant folder
//
// check.mjs is one zero-dependency ES module for Node 18+: learners run it with `node check.mjs`.
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const CHECK_OUT = path.join(ROOT, 'dist-tools/check.mjs');
export const ZIP_TOOL_OUT = path.join(ROOT, 'dist-tools/zip.mjs');
export const LEARNC_H = path.join(ROOT, 'src/runtime/c/learnc.h');

function runnerVersion() {
  const src = readFileSync(path.join(ROOT, 'src/testing/token.ts'), 'utf8');
  return /export const RUNNER_VERSION = (\d+)/.exec(src)?.[1] ?? '?';
}

/** Bundles check.mjs. Returns its path and size. */
export async function buildCheck({ outfile = CHECK_OUT } = {}) {
  const banner = [
    '#!/usr/bin/env node',
    `// check.mjs R${runnerVersion()}: the local test runner of The Definitive C Course (MIT License).`,
    '// Generated by tools/check/build.mjs from tools/check/src/check.ts and src/testing/. Do not edit.',
    '// Usage: node check.mjs [folder] [--hint] [--only NAME] [--cc COMPILER] [--json]   (or: make test)',
  ].join('\n');
  await build({
    entryPoints: [path.join(ROOT, 'tools/check/src/check.ts')],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node18',
    banner: { js: banner },
    charset: 'utf8',
    legalComments: 'none',
    logLevel: 'warning',
  });
  return { outfile, bytes: statSync(outfile).size };
}

/** Bundles the zip builder (it needs yaml and fflate, so it is a separate, CI-only file). */
export async function buildZipTool({ outfile = ZIP_TOOL_OUT } = {}) {
  await build({
    entryPoints: [path.join(ROOT, 'tools/check/src/zip-cli.ts')],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node18',
    // Bundled CommonJS dependencies may call require() for Node built-ins.
    banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
    logLevel: 'warning',
  });
  return outfile;
}

/** Loads the bundled zip helpers (zipProject, projectEntries, zipInput). */
export async function loadZipTool() {
  const file = await buildZipTool();
  return import(`${pathToFileURL(file).href}?t=${statSync(file).mtimeMs}`);
}

function parseCli(argv) {
  const opts = { into: undefined, zip: undefined, out: undefined, solution: false, seed: undefined };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const next = () => {
      if (i + 1 >= argv.length) throw new Error(`${a} needs a value`);
      return argv[++i];
    };
    if (a === '--into') opts.into = next();
    else if (a === '--zip') opts.zip = next();
    else if (a === '--out') opts.out = next();
    else if (a === '--seed') opts.seed = next();
    else if (a === '--solution') opts.solution = true;
    else throw new Error(`unknown argument ${a}`);
  }
  if (opts.zip && !opts.out) throw new Error('--zip needs --out <file.zip>');
  return opts;
}

async function cli() {
  const opts = parseCli(process.argv.slice(2));
  const { outfile, bytes } = await buildCheck();
  console.log(`check.mjs: ${path.relative(process.cwd(), outfile)} (${(bytes / 1024).toFixed(1)} KB)`);
  if (opts.into) {
    const dest = path.resolve(opts.into, 'downloads/check.mjs');
    mkdirSync(path.dirname(dest), { recursive: true });
    copyFileSync(outfile, dest);
    console.log(`check.mjs: copied to ${path.relative(process.cwd(), dest)}`);
  }
  if (opts.zip) {
    const { zipProject } = await loadZipTool();
    const files = zipProject({
      dir: path.resolve(opts.zip), out: path.resolve(opts.out), solution: opts.solution, seed: opts.seed,
      checkMjsPath: outfile, learncPath: LEARNC_H,
    });
    console.log(`zip: ${opts.out}\n  ${files.join('\n  ')}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  cli().catch(e => {
    console.error(`build.mjs: ${e.message}`);
    process.exit(1);
  });
}
